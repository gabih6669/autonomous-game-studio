import { cp, copyFile, mkdir, rm, stat } from 'node:fs/promises';
import { resolve } from 'node:path';
const root=resolve(import.meta.dirname,'..');
const out=resolve(root,'dist');
await rm(out,{recursive:true,force:true});
await mkdir(out,{recursive:true});
await copyFile(resolve(root,'index.html'),resolve(out,'index.html'));
await copyFile(resolve(root,'style.css'),resolve(out,'style.css'));
await cp(resolve(root,'src'),resolve(out,'src'),{recursive:true});
await cp(resolve(root,'assets'),resolve(out,'assets'),{recursive:true});
for(const path of ['index.html','style.css','src/main.js','src/sim.js','assets/crest.svg'])await stat(resolve(out,path));
console.log('Build verified: dist/ has a complete offline browser game.');
